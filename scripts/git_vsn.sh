#!/bin/sh
# Writes include/git_vsn.hrl: the commit suffix appended to the version in the
# Server header (MeowMeow/<version><suffix>). Run by the rebar3 pre-compile
# hook, from any directory.
#
#   .<sha>         clean checkout of commit <sha>
#   .<sha>.dirty   tracked files have uncommitted changes
#   .unknown       neither a git checkout nor GIT_SHA given
#
# Container builds have no .git, so they pass the commit in the environment:
# GIT_SHA is the short hash and GIT_DIRTY is a flag (empty, 0, false or no
# means clean, anything else means dirty).
set -eu
cd "$(dirname "$0")/.."

if [ -n "${GIT_SHA:-}" ]; then
  sha=$GIT_SHA
  dirty=${GIT_DIRTY:-}
elif sha=$(git rev-parse --short HEAD 2>/dev/null); then
  dirty=$(git diff --quiet HEAD -- 2>/dev/null || echo dirty)
else
  sha=unknown
  dirty=
fi

case "$dirty" in
  ""|0|false|no) suffix=".$sha" ;;
  *)             suffix=".$sha.dirty" ;;
esac

printf '%%%% Generated by scripts/git_vsn.sh before every compile; do not edit.\n-define(GIT_VSN, "%s").\n' \
  "$suffix" > include/git_vsn.hrl
