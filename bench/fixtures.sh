#!/bin/sh
# Generates the benchmark fixtures inside the image (see bench/Dockerfile):
#   $1/index.html, $1/bench/{1k,64k,1m,16m}.bin  - static files
#   $2/filler.conf                               - 256 non-matching Route blocks
set -eu

WWW="${1:-/var/www}"
CONF="${2:-/etc/nya}"

mkdir -p "$WWW/bench" "$CONF"

cat > "$WWW/index.html" <<'HTML'
<!doctype html>
<html>
<head><meta charset="utf-8"><title>MeowMeow benchmark</title></head>
<body><h1>Nya~ It works!</h1><p>This page is served by the benchmark image.</p></body>
</html>
HTML

head -c 1024                  /dev/urandom > "$WWW/bench/1k.bin"
head -c $((64 * 1024))        /dev/urandom > "$WWW/bench/64k.bin"
head -c $((1024 * 1024))      /dev/urandom > "$WWW/bench/1m.bin"
head -c $((16 * 1024 * 1024)) /dev/urandom > "$WWW/bench/16m.bin"

{
  echo "# Generated by bench/fixtures.sh: routes that never match a benchmark"
  echo "# request, so every request to /deep walks past all of them first."
  i=1
  while [ "$i" -le 256 ]; do
    printf 'Route /filler-%d\n Abort 410\nEnd\n\n' "$i"
    i=$((i + 1))
  done
} > "$CONF/filler.conf"

ls -l "$WWW/bench"
echo "filler.conf: $(grep -c '^Route' "$CONF/filler.conf") routes"
